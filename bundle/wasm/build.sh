#!/usr/bin/env sh
# Builds the .justspeech reader into a consumer's checkout, which carries only these outputs:
# every reader change reaches it through this script.
#   ./build.sh ../../../just_speech_web/src/wasm/bundle
#   ./build.sh ../../../just_speech_infra/lambda/ppt-imager/src/wasm/bundle
# Needs `rustup target add wasm32-unknown-unknown` and `cargo install wasm-pack`.
set -eu

here=$(cd "$(dirname "$0")" && pwd)
out=${1:?usage: build.sh <install directory>}

wasm-pack build "$here" --release --target web --out-dir "$here/pkg" --out-name bundle_wasm

mkdir -p "$out"
for f in bundle_wasm.js bundle_wasm.d.ts bundle_wasm_bg.wasm bundle_wasm_bg.wasm.d.ts; do
  cp "$here/pkg/$f" "$out/$f"
done

source=$(git -C "$here" describe --always --dirty)
cat > "$out/README.md" <<README
# bundle

The shared \`.justspeech\` reader (\`just_speech_core/bundle/rust\`) compiled to WebAssembly; the
format is \`bundle/JUSTSPEECH_FORMAT.md\` there. Generated by \`bundle/wasm/build.sh\` in that repo;
do not edit these files here. A reader change is made there, tested with \`cargo test -p bundle\`,
and reinstalled by rerunning the script.

Source: just_speech_core@$source
Toolchain: $(wasm-pack --version), $(rustc --version)

The browser initializes it with the default export; Node with \`initSync({ module: <the .wasm
bytes> })\`.

- \`new BundleFile(bytes)\` validates the whole file, every slide included, and throws an \`Error\`
  named \`BundleDamaged\` (only another copy of the file helps) or \`BundleUpdateRequired\` (a newer
  reader does). The object lives in wasm memory with a copy of the bytes: \`free()\` it when done.
- \`title\` (empty for none), \`script\`, \`mappings\` (\`Mapping[]\`, the server's \`SlideMapping\`;
  empty when the file has none), \`slideCount\` (0 for no deck), \`skipped\` (part ids left out,
  for logs).
- \`slide(index)\` returns the PNG of slide \`index\`, 0-based. Its header was checked, its pixels
  were not: decode it as untrusted.
README
echo "installed into $out ($source)"
