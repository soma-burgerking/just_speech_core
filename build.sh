#!/usr/bin/env sh
# Builds the browser slide counter into a just_speech_web checkout, which carries only these
# outputs: every counter change reaches the web through this script.
#   ./build.sh ../../../../just_speech_web
# Needs `rustup target add wasm32-unknown-unknown` and `cargo install wasm-pack`.
set -eu

here=$(cd "$(dirname "$0")" && pwd)
web=${1:?usage: build.sh <just_speech_web checkout>}
out="$web/src/wasm/slide-count"

wasm-pack build "$here" --release --target web --out-dir "$here/pkg" --out-name slides_wasm

mkdir -p "$out"
for f in slides_wasm.js slides_wasm.d.ts slides_wasm_bg.wasm slides_wasm_bg.wasm.d.ts; do
  cp "$here/pkg/$f" "$out/$f"
done

source=$(git -C "$here" describe --always --dirty)
cat > "$out/README.md" <<README
# slide-count

The app's Rust slide counter (\`just_speech_app/rust/crates/slides\`) compiled to WebAssembly.
Generated by \`rust/crates/slides-wasm/build.sh\` in that repo; do not edit these files here.
A counter change is made there, tested with \`cargo test -p slides\`, and reinstalled by rerunning
the script.

Source: just_speech_app@$source
Toolchain: $(wasm-pack --version), $(rustc --version)

\`count_slides(bytes, format)\` takes the file's bytes and its extension (\`pptx | ppt | odp |
pdf\`) and returns the number of slides the render pipeline will produce (hidden slides included).
It throws when the bytes cannot be read as that format.
README
echo "installed into $out ($source)"
