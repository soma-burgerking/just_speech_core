#!/usr/bin/env sh
# Builds the browser slide reader into a just_speech_web checkout, which carries only these
# outputs: every reader change reaches the web through this script.
#   ./build.sh ../../just_speech_web
# Needs `rustup target add wasm32-unknown-unknown` and `cargo install wasm-pack`.
set -eu

here=$(cd "$(dirname "$0")" && pwd)
web=${1:?usage: build.sh <just_speech_web checkout>}
out="$web/src/wasm/slides"

wasm-pack build "$here" --release --target web --out-dir "$here/pkg" --out-name slides_wasm

mkdir -p "$out"
for f in slides_wasm.js slides_wasm.d.ts slides_wasm_bg.wasm slides_wasm_bg.wasm.d.ts; do
  cp "$here/pkg/$f" "$out/$f"
done

source=$(git -C "$here" describe --always --dirty)
cat > "$out/README.md" <<README
# slides

The shared Rust slide reader (\`just_speech_core/crates/slides\`) compiled to WebAssembly.
Generated by \`wasm/build.sh\` in that repo; do not edit these files here.
A reader change is made there, tested with \`cargo test -p slides\`, and reinstalled by rerunning
the script.

Source: just_speech_core@$source
Toolchain: $(wasm-pack --version), $(rustc --version)

Both functions take the file's bytes and its extension (\`pptx | ppt | odp | pdf\`) and throw when
the bytes cannot be read as that format.

- \`count_slides(bytes, format)\` returns the number of slides the render pipeline will produce
  (hidden slides included).
- \`slide_texts(bytes, format)\` returns one \`SlideText\` per slide in that order — its 1-based
  \`slide\`, the title placeholder and the speaker notes (paragraphs joined by \`\\n\`), each
  \`undefined\` when the slide has none. Only \`pptx\` and \`odp\` store text; the other formats throw.
  The objects live in wasm memory: read them, then \`free()\` each.
README
echo "installed into $out ($source)"
